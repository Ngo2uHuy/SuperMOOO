using System.Text.Json;
using SuperMOOO.Core.Publishing;
using static SuperMOOO.Data.Repositories.Publishing.PubSql;

namespace SuperMOOO.Data.Repositories.Publishing;

[Service(As = [typeof(IProductionRepository)])]
public sealed class ProductionRepository(IDbConnectionFactory factory) : IProductionRepository
{
    private const int IdChunk = 500;
    private const string Columns = """
        id, producer, campaign_id, topic, language, aspect, target_duration_sec, notes, state, progress, message, producer_job_id,
        content_ids_json, auto_generated, created_at, sent_at, updated_at, expires_at
        """;

    private sealed class Row
    {
        public string Id { get; set; } = "";
        public string Producer { get; set; } = "";
        public string? CampaignId { get; set; }
        public string Topic { get; set; } = "";
        public string Language { get; set; } = "";
        public string Aspect { get; set; } = ProductionAspects.Landscape;
        public int? TargetDurationSec { get; set; }
        public string? Notes { get; set; }
        public ProductionState State { get; set; }
        public int Progress { get; set; }
        public string? Message { get; set; }
        public string? ProducerJobId { get; set; }
        public string ContentIdsJson { get; set; } = "[]";
        public bool AutoGenerated { get; set; }
        public long CreatedAt { get; set; }
        public long? SentAt { get; set; }
        public long UpdatedAt { get; set; }
        public long? ExpiresAt { get; set; }

        public ProductionRequest ToRequest() => new()
        {
            Id = Id, Producer = Producer, CampaignId = CampaignId, Topic = Topic, Language = Language, Aspect = Aspect,
            TargetDurationSec = TargetDurationSec, Notes = Notes, State = State, Progress = Progress, Message = Message, ProducerJobId = ProducerJobId,
            ContentIdsJson = ContentIdsJson, AutoGenerated = AutoGenerated, CreatedUtc = FromMs(CreatedAt), SentUtc = FromMs(SentAt),
            UpdatedUtc = FromMs(UpdatedAt), ExpiresUtc = FromMs(ExpiresAt)
        };
    }

    private sealed class AckRow
    {
        public string Id { get; set; } = "";
        public string RequestId { get; set; } = "";
        public string State { get; set; } = "";
        public int Progress { get; set; }
        public string? Message { get; set; }
        public string? ProducerJobId { get; set; }
        public long StatusUpdatedAt { get; set; }
        public long ReceivedAt { get; set; }
    }

    // Danh sách trạng thái được nối từ hằng số enum (không phải input người dùng) nên an toàn khi đưa vào IN (...).
    private static string InList(IEnumerable<ProductionState> states) => string.Join(',', states.Select(s => $"'{s}'"));

    public async Task AddAsync(ProductionRequest r, CancellationToken ct)
    {
        await using var db = factory.Open();
        await db.ExecuteAsync(new CommandDefinition("""
            INSERT INTO pub_production_requests(id, producer, campaign_id, topic, language, aspect, target_duration_sec, notes, state, progress,
              message, producer_job_id, content_ids_json, auto_generated, created_at, sent_at, updated_at, expires_at)
            VALUES (@Id, @Producer, @CampaignId, @Topic, @Language, @Aspect, @TargetDurationSec, @Notes, @State, @Progress,
              @Message, @ProducerJobId, @ContentIdsJson, @AutoGenerated, @created, @sent, @updated, @expires)
            """,
            new
            {
                r.Id, r.Producer, r.CampaignId, r.Topic, r.Language, r.Aspect, r.TargetDurationSec, r.Notes, State = r.State.ToString(), r.Progress,
                r.Message, r.ProducerJobId, r.ContentIdsJson, r.AutoGenerated, created = ToMs(r.CreatedUtc), sent = ToMs(r.SentUtc),
                updated = ToMs(r.UpdatedUtc), expires = ToMs(r.ExpiresUtc)
            }, cancellationToken: ct));
    }

    public async Task<ProductionRequest?> GetAsync(string id, CancellationToken ct)
    {
        await using var db = factory.Open();
        var row = await db.QueryFirstOrDefaultAsync<Row>(new CommandDefinition(
            $"SELECT {Columns} FROM pub_production_requests WHERE id = @id", new { id }, cancellationToken: ct));
        return row?.ToRequest();
    }

    public async Task<(IReadOnlyList<ProductionRequest> Items, int Total)> ListAsync(
        ProductionState? state, bool open, string? campaignId, int page, int pageSize, CancellationToken ct)
    {
        await using var db = factory.Open();
        var args = new { state = state?.ToString(), open, campaignId, size = pageSize, offset = (page - 1) * pageSize };
        var where = $"""
            WHERE (@state IS NULL OR state = @state) AND (@open = 0 OR state IN ({InList(ProductionStates.Open)}))
              AND (@campaignId IS NULL OR campaign_id = @campaignId)
            """;
        var total = await db.ExecuteScalarAsync<int>(new CommandDefinition("SELECT COUNT(*) FROM pub_production_requests " + where, args,
            cancellationToken: ct));
        var items = (await db.QueryAsync<Row>(new CommandDefinition(
            $"SELECT {Columns} FROM pub_production_requests {where} ORDER BY created_at DESC, id LIMIT @size OFFSET @offset",
            args, cancellationToken: ct))).Select(r => r.ToRequest()).ToList();
        return (items, total);
    }

    public async Task<IReadOnlyList<ProductionRequest>> ListByStatesAsync(
        IReadOnlyCollection<ProductionState> states, string? producer, DateTimeOffset? updatedSinceUtc, CancellationToken ct)
    {
        if (states.Count == 0) return [];
        await using var db = factory.Open();
        return (await db.QueryAsync<Row>(new CommandDefinition($"""
            SELECT {Columns} FROM pub_production_requests
            WHERE state IN ({InList(states)}) AND (@producer IS NULL OR producer = @producer) AND (@since IS NULL OR updated_at >= @since)
            ORDER BY created_at, id
            """, new { producer, since = ToMs(updatedSinceUtc) }, cancellationToken: ct))).Select(r => r.ToRequest()).ToList();
    }

    public async Task<bool> UpdateAsync(ProductionRequest r, IReadOnlyCollection<ProductionState> from, CancellationToken ct)
    {
        await using var db = factory.Open();
        return await db.ExecuteAsync(new CommandDefinition($"""
            UPDATE pub_production_requests SET state = @State, progress = @Progress, message = @Message, producer_job_id = @ProducerJobId,
              content_ids_json = @ContentIdsJson, sent_at = @sent, updated_at = @updated
            WHERE id = @Id AND state IN ({InList(from)})
            """,
            new
            {
                r.Id, State = r.State.ToString(), r.Progress, r.Message, r.ProducerJobId, r.ContentIdsJson, sent = ToMs(r.SentUtc),
                updated = ToMs(r.UpdatedUtc)
            }, cancellationToken: ct)) > 0;
    }

    public async Task<bool> AddAckAsync(ProducerAcknowledgement a, CancellationToken ct)
    {
        await using var db = factory.Open();
        return await db.ExecuteAsync(new CommandDefinition("""
            INSERT INTO pub_producer_acknowledgements(id, request_id, state, progress, message, producer_job_id, status_updated_at, received_at)
            VALUES (@Id, @RequestId, @State, @Progress, @Message, @ProducerJobId, @statusUpdated, @received)
            ON CONFLICT(request_id, state, status_updated_at) DO NOTHING
            """,
            new
            {
                a.Id, a.RequestId, a.State, a.Progress, a.Message, a.ProducerJobId, statusUpdated = ToMs(a.StatusUpdatedUtc),
                received = ToMs(a.ReceivedUtc)
            }, cancellationToken: ct)) > 0;
    }

    public async Task<IReadOnlyList<ProducerAcknowledgement>> ListAcksAsync(string requestId, CancellationToken ct)
    {
        await using var db = factory.Open();
        return (await db.QueryAsync<AckRow>(new CommandDefinition("""
            SELECT id, request_id, state, progress, message, producer_job_id, status_updated_at, received_at
            FROM pub_producer_acknowledgements WHERE request_id = @requestId ORDER BY status_updated_at, received_at, id
            """, new { requestId }, cancellationToken: ct)))
            .Select(a => new ProducerAcknowledgement
            {
                Id = a.Id, RequestId = a.RequestId, State = a.State, Progress = a.Progress, Message = a.Message, ProducerJobId = a.ProducerJobId,
                StatusUpdatedUtc = FromMs(a.StatusUpdatedAt), ReceivedUtc = FromMs(a.ReceivedAt)
            }).ToList();
    }

    public async Task<int> CountOpenAsync(string? producer, string? campaignId, CancellationToken ct)
    {
        await using var db = factory.Open();
        return await db.ExecuteScalarAsync<int>(new CommandDefinition($"""
            SELECT COUNT(*) FROM pub_production_requests
            WHERE state IN ({InList(ProductionStates.Open)}) AND (@producer IS NULL OR producer = @producer)
              AND (@campaignId IS NULL OR campaign_id = @campaignId)
            """, new { producer, campaignId }, cancellationToken: ct));
    }

    public async Task<int> CountCreatedSinceAsync(string producer, DateTimeOffset sinceUtc, CancellationToken ct)
    {
        await using var db = factory.Open();
        return await db.ExecuteScalarAsync<int>(new CommandDefinition(
            "SELECT COUNT(*) FROM pub_production_requests WHERE producer = @producer AND created_at >= @since AND state <> 'Cancelled'",
            new { producer, since = ToMs(sinceUtc) }, cancellationToken: ct));
    }

    public async Task<IReadOnlyList<ProductionRequest>> ListRecentForCampaignAsync(string campaignId, int take, CancellationToken ct)
    {
        await using var db = factory.Open();
        return (await db.QueryAsync<Row>(new CommandDefinition(
            $"SELECT {Columns} FROM pub_production_requests WHERE campaign_id = @campaignId ORDER BY created_at DESC, id LIMIT @take",
            new { campaignId, take }, cancellationToken: ct))).Select(r => r.ToRequest()).ToList();
    }

    public async Task<IReadOnlyDictionary<string, int>> LinkedContentCountsAsync(IReadOnlyCollection<string> requestIds, CancellationToken ct)
    {
        var result = new Dictionary<string, int>();
        await using var db = factory.Open();
        foreach (var chunk in requestIds.Chunk(IdChunk))
            foreach (var row in await db.QueryAsync<(string RequestId, int N)>(new CommandDefinition(
                         "SELECT request_id AS RequestId, COUNT(*) AS N FROM pub_content_items WHERE request_id IN @chunk GROUP BY request_id",
                         new { chunk }, cancellationToken: ct)))
                result[row.RequestId] = row.N;
        return result;
    }

    public async Task<IReadOnlyList<(string Id, string Title)>> ListLinkedContentAsync(string requestId, CancellationToken ct)
    {
        await using var db = factory.Open();
        return (await db.QueryAsync<(string Id, string Title)>(new CommandDefinition(
            "SELECT id AS Id, title AS Title FROM pub_content_items WHERE request_id = @requestId ORDER BY imported_at, id",
            new { requestId }, cancellationToken: ct))).ToList();
    }

    public async Task<IReadOnlyDictionary<string, string>> RequestCampaignsAsync(CancellationToken ct)
    {
        await using var db = factory.Open();
        return (await db.QueryAsync<(string Id, string CampaignId)>(new CommandDefinition(
                "SELECT id AS Id, campaign_id AS CampaignId FROM pub_production_requests WHERE campaign_id IS NOT NULL", cancellationToken: ct)))
            .ToDictionary(x => x.Id, x => x.CampaignId);
    }
}

[Service(As = [typeof(IProductionConfigRepository)])]
public sealed class ProductionConfigRepository(IDbConnectionFactory factory) : IProductionConfigRepository
{
    private const string CampaignColumns = """
        campaign_id, enabled, topics_json, language, aspect, buffer_days, target_days, max_order, preferred_producer, replenishing
        """;

    private sealed class ProducerRow
    {
        public string Producer { get; set; } = "";
        public string ExchangeDir { get; set; } = "";
        public bool Enabled { get; set; }
        public int MaxOpenRequests { get; set; }
        public int DailyRequestBudget { get; set; }
        public string SupportedAspectsJson { get; set; } = "[]";
        public int AckTimeoutMinutes { get; set; }
        public int RequestTtlHours { get; set; }
        public long UpdatedAt { get; set; }
    }

    private sealed class CampaignRow
    {
        public string CampaignId { get; set; } = "";
        public bool Enabled { get; set; }
        public string TopicsJson { get; set; } = "[]";
        public string? Language { get; set; }
        public string? Aspect { get; set; }
        public double BufferDays { get; set; }
        public double TargetDays { get; set; }
        public int MaxOrder { get; set; }
        public string? PreferredProducer { get; set; }
        public bool Replenishing { get; set; }
    }

    private static CampaignProduction ToDomain(CampaignRow r) => new()
    {
        CampaignId = r.CampaignId, Enabled = r.Enabled, Topics = StringList(r.TopicsJson), Language = r.Language, Aspect = r.Aspect,
        BufferDays = r.BufferDays, TargetDays = r.TargetDays, MaxOrder = r.MaxOrder, PreferredProducer = r.PreferredProducer,
        Replenishing = r.Replenishing
    };

    public async Task<IReadOnlyList<ProducerConfig>> ListProducersAsync(CancellationToken ct)
    {
        await using var db = factory.Open();
        return (await db.QueryAsync<ProducerRow>(new CommandDefinition("""
            SELECT producer, exchange_dir, enabled, max_open_requests, daily_request_budget, supported_aspects_json, ack_timeout_minutes,
              request_ttl_hours, updated_at
            FROM pub_producer_configs ORDER BY producer
            """, cancellationToken: ct)))
            .Select(r => new ProducerConfig
            {
                Producer = r.Producer, Enabled = r.Enabled, MaxOpenRequests = r.MaxOpenRequests,
                DailyRequestBudget = r.DailyRequestBudget, SupportedAspects = StringList(r.SupportedAspectsJson),
                AckTimeoutMinutes = r.AckTimeoutMinutes, RequestTtlHours = r.RequestTtlHours, UpdatedUtc = FromMs(r.UpdatedAt)
            }).ToList();
    }

    public async Task SaveProducerAsync(ProducerConfig c, CancellationToken ct)
    {
        await using var db = factory.Open();
        await db.ExecuteAsync(new CommandDefinition("""
            INSERT INTO pub_producer_configs(producer, exchange_dir, enabled, max_open_requests, daily_request_budget, supported_aspects_json,
              ack_timeout_minutes, request_ttl_hours, updated_at)
            VALUES (@Producer, @ExchangeDir, @Enabled, @MaxOpenRequests, @DailyRequestBudget, @Aspects, @AckTimeoutMinutes, @RequestTtlHours, @updated)
            ON CONFLICT(producer) DO UPDATE SET exchange_dir = excluded.exchange_dir, enabled = excluded.enabled,
              max_open_requests = excluded.max_open_requests, daily_request_budget = excluded.daily_request_budget,
              supported_aspects_json = excluded.supported_aspects_json, ack_timeout_minutes = excluded.ack_timeout_minutes,
              request_ttl_hours = excluded.request_ttl_hours, updated_at = excluded.updated_at
            """,
            new
            {
                c.Producer, ExchangeDir = "", c.Enabled, c.MaxOpenRequests, c.DailyRequestBudget,
                Aspects = JsonSerializer.Serialize(c.SupportedAspects, Json), c.AckTimeoutMinutes, c.RequestTtlHours, updated = ToMs(c.UpdatedUtc)
            }, cancellationToken: ct));
    }

    public async Task<CampaignProduction?> GetCampaignAsync(string campaignId, CancellationToken ct)
    {
        await using var db = factory.Open();
        var row = await db.QueryFirstOrDefaultAsync<CampaignRow>(new CommandDefinition(
            $"SELECT {CampaignColumns} FROM pub_campaign_production WHERE campaign_id = @campaignId", new { campaignId }, cancellationToken: ct));
        return row is null ? null : ToDomain(row);
    }

    public async Task<IReadOnlyList<CampaignProduction>> ListCampaignsAsync(CancellationToken ct)
    {
        await using var db = factory.Open();
        return (await db.QueryAsync<CampaignRow>(new CommandDefinition(
                $"SELECT {CampaignColumns} FROM pub_campaign_production ORDER BY campaign_id", cancellationToken: ct)))
            .Select(ToDomain).ToList();
    }

    public async Task SaveCampaignAsync(CampaignProduction s, DateTimeOffset now, CancellationToken ct)
    {
        await using var db = factory.Open();
        // Không ghi đè replenishing: cờ đó do bộ đặt hàng tự quản lý.
        await db.ExecuteAsync(new CommandDefinition("""
            INSERT INTO pub_campaign_production(campaign_id, enabled, topics_json, language, aspect, buffer_days, target_days, max_order,
              preferred_producer, replenishing, updated_at)
            VALUES (@CampaignId, @Enabled, @Topics, @Language, @Aspect, @BufferDays, @TargetDays, @MaxOrder, @PreferredProducer, 0, @now)
            ON CONFLICT(campaign_id) DO UPDATE SET enabled = excluded.enabled, topics_json = excluded.topics_json, language = excluded.language,
              aspect = excluded.aspect, buffer_days = excluded.buffer_days, target_days = excluded.target_days, max_order = excluded.max_order,
              preferred_producer = excluded.preferred_producer, updated_at = excluded.updated_at,
              replenishing = CASE WHEN excluded.enabled = 0 THEN 0 ELSE pub_campaign_production.replenishing END
            """,
            new
            {
                s.CampaignId, s.Enabled, Topics = JsonSerializer.Serialize(s.Topics, Json), s.Language, s.Aspect, s.BufferDays,
                s.TargetDays, s.MaxOrder, s.PreferredProducer, now = ToMs(now)
            }, cancellationToken: ct));
    }

    public async Task SetReplenishingAsync(string campaignId, bool value, CancellationToken ct)
    {
        await using var db = factory.Open();
        await db.ExecuteAsync(new CommandDefinition("UPDATE pub_campaign_production SET replenishing = @value WHERE campaign_id = @campaignId",
            new { campaignId, value }, cancellationToken: ct));
    }
}
