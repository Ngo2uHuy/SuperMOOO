namespace SuperMOOO.Core.Publishing;

/// <summary>Draft: đã ghi yêu cầu, chưa xếp job. Running: job sản xuất đã xếp (hoặc đang chạy); Completed khi job xong.</summary>
public enum ProductionState { Draft, Sent, Accepted, Rejected, Running, Completed, Failed, Expired, Cancelled }

public static class Producers
{
    public const string VideoC = "videoc";
    public const string AIVideoStudio = "aivideostudio";
    public static readonly string[] All = [VideoC, AIVideoStudio];

    public static bool IsKnown(string? producer) => producer is not null && All.Contains(producer, StringComparer.Ordinal);

    public static string DisplayName(string producer) => producer == AIVideoStudio ? "Talkshow (S03)" : producer == VideoC ? "Whiteboard (S18)" : producer;
}

public static class ProductionAspects
{
    public const string Landscape = "16:9";
    public const string Portrait = "9:16";

    public static bool IsValid(string? aspect) => aspect is Landscape or Portrait;
}

public static class ProductionStates
{
    /// <summary>Yêu cầu còn chiếm hạn mức: chưa có kết quả cuối.</summary>
    public static readonly ProductionState[] Open = [ProductionState.Draft, ProductionState.Sent, ProductionState.Accepted, ProductionState.Running];

    /// <summary>Kết quả cuối do producer báo; status tới sau đó không đổi lại trạng thái.</summary>
    public static readonly ProductionState[] ProducerFinal = [ProductionState.Rejected, ProductionState.Completed, ProductionState.Failed];

    public static bool IsOpen(ProductionState s) => Open.Contains(s);
}

public sealed class ProductionRequest
{
    public string Id { get; init; } = "";
    public string Producer { get; init; } = "";
    public string? CampaignId { get; init; }
    public string Topic { get; init; } = "";
    public string Language { get; init; } = "";
    public string Aspect { get; init; } = ProductionAspects.Landscape;
    public int? TargetDurationSec { get; init; }
    public string? Notes { get; init; }
    public ProductionState State { get; set; }
    public int Progress { get; set; }
    public string? Message { get; set; }
    public string? ProducerJobId { get; set; }
    public string ContentIdsJson { get; set; } = "[]";
    public bool AutoGenerated { get; init; }
    public DateTimeOffset CreatedUtc { get; init; }
    public DateTimeOffset? SentUtc { get; set; }
    public DateTimeOffset UpdatedUtc { get; set; }
    public DateTimeOffset? ExpiresUtc { get; init; }
}

public sealed class ProducerAcknowledgement
{
    public string Id { get; init; } = "";
    public string RequestId { get; init; } = "";
    public string State { get; init; } = "";
    public int Progress { get; init; }
    public string? Message { get; init; }
    public string? ProducerJobId { get; init; }
    public DateTimeOffset StatusUpdatedUtc { get; init; }
    public DateTimeOffset ReceivedUtc { get; init; }
}

public sealed class ProducerConfig
{
    public string Producer { get; init; } = "";
    public bool Enabled { get; set; } = true;
    public int MaxOpenRequests { get; set; } = 2;
    public int DailyRequestBudget { get; set; } = 10;
    public IReadOnlyList<string> SupportedAspects { get; set; } = [ProductionAspects.Landscape];
    /// <summary>Không còn dùng (producer chạy trong tiến trình, không chờ phản hồi); giữ vì cột DB.</summary>
    public int AckTimeoutMinutes { get; set; } = 30;
    public int RequestTtlHours { get; set; } = 24;
    public DateTimeOffset UpdatedUtc { get; set; }

    /// <summary>VideoC (whiteboard) làm được cả hai tỉ lệ; AIVideoStudio (Talkshow) chỉ 16:9.</summary>
    public static ProducerConfig Default(string producer) => new()
    {
        Producer = producer,
        SupportedAspects = producer == Producers.VideoC ? [ProductionAspects.Landscape, ProductionAspects.Portrait] : [ProductionAspects.Landscape]
    };
}

/// <summary>Cấu hình "Tự đặt sản xuất" của một chiến dịch; mặc định tắt.</summary>
public sealed class CampaignProduction
{
    public string CampaignId { get; init; } = "";
    public bool Enabled { get; set; }
    public IReadOnlyList<string> Topics { get; set; } = [];
    /// <summary>null = lấy từ quy tắc chiến dịch (không có thì "vi").</summary>
    public string? Language { get; set; }
    /// <summary>null = suy từ quy tắc chiến dịch (Portrait → 9:16, còn lại 16:9).</summary>
    public string? Aspect { get; set; }
    public double BufferDays { get; set; } = 3;
    public double TargetDays { get; set; } = 7;
    public int MaxOrder { get; set; } = 5;
    public string? PreferredProducer { get; set; }
    public bool Replenishing { get; set; }
}
