using Microsoft.Extensions.Logging;
using SuperMOOO.Publishing.Algorithms;
using SuperMOOO.Publishing.Automation;
using SuperMOOO.Publishing.Contracts;
using SuperMOOO.Publishing.Http;
using SuperMOOO.Publishing.OAuth;
using SuperMOOO.Publishing.Publications;

namespace SuperMOOO.Publishing.Production;

public sealed record ProductionOrderResult(int Created, IReadOnlyList<string> Notes);

/// <param name="Stock">Số nội dung khớp quy tắc, chưa hết hạn, chưa đăng/xếp lịch trên kênh thiếu nhất của chiến dịch.</param>
public sealed record StockMeasure(int Stock, double PostsPerDay);

public sealed record CampaignProductionView(CampaignProduction Settings, StockMeasure Measure, int OpenRequests);

/// <summary>
/// Đặt sản xuất tự động theo chiến dịch: tồn = nội dung khớp quy tắc chưa đăng; ReorderPoint(bài/ngày × ngày đệm) → một yêu cầu cho mỗi
/// chiến dịch tại một thời điểm. automation_paused chặn; mặc định tắt theo chiến dịch.
/// </summary>
[Service]
public sealed class ProductionOrderPlanner(
    ProductionService production,
    IProductionRepository requests,
    IProductionConfigRepository configs,
    ICampaignRepository campaigns,
    IContentRepository contents,
    IDestinationRepository destinations,
    IActionRequiredRepository actions,
    IPublishSettingsStore settings,
    IClock clock,
    ILogger<ProductionOrderPlanner> logger)
{
    private static readonly ProductionState[] Unproductive = [ProductionState.Rejected, ProductionState.Failed, ProductionState.Expired];
    /// <summary>Producer vừa lỗi: không đặt lại ngay (mỗi lần đặt tốn thời gian máy).</summary>
    private static readonly TimeSpan FailureCooldown = TimeSpan.FromMinutes(30);
    /// <summary>Job xong nhưng video chưa vào kho: vẫn coi là đang chờ để không đặt trùng.</summary>
    private static readonly TimeSpan ImportGrace = TimeSpan.FromMinutes(10);

    private readonly SemaphoreSlim _gate = new(1, 1);

    public async Task<ProductionOrderResult> RunAsync(CancellationToken ct)
    {
        await _gate.WaitAsync(ct);
        try
        {
            if (PlatformFlags.IsTrue(await settings.GetAsync(SettingKeys.AutomationPaused, ct)))
                return new ProductionOrderResult(0, ["Đăng tự động đang tạm dừng: không đặt sản xuất tự động."]);

            var enabled = (await configs.ListCampaignsAsync(ct)).Where(c => c.Enabled).ToList();
            if (enabled.Count == 0) return new ProductionOrderResult(0, []);

            var plans = await LoadPlansAsync(ct);
            var measures = await MeasureAsync(plans, ct);
            var created = 0;
            var notes = new List<string>();
            foreach (var cp in enabled)
            {
                var plan = plans.GetValueOrDefault(cp.CampaignId);
                if (plan is null || plan.Campaign.Status != CampaignStatus.Active) continue;
                if (cp.Topics.Count == 0)
                {
                    notes.Add($"\"{plan.Campaign.Name}\": bật tự đặt sản xuất nhưng chưa có chủ đề.");
                    continue;
                }
                if (!measures.TryGetValue(cp.CampaignId, out var m))
                {
                    notes.Add($"\"{plan.Campaign.Name}\": chưa có kênh đích khả dụng để tính tồn.");
                    continue;
                }
                if (await TryOrderAsync(plan, cp, m, notes, ct)) created++;
            }
            return new ProductionOrderResult(created, notes);
        }
        finally { _gate.Release(); }
    }

    private async Task<bool> TryOrderAsync(CampaignPlan plan, CampaignProduction cp, StockMeasure m, List<string> notes, CancellationToken ct)
    {
        var now = clock.UtcNow;
        var name = plan.Campaign.Name;
        var recent = await requests.ListRecentForCampaignAsync(cp.CampaignId, Math.Max(cp.Topics.Count * 2, 10), ct);
        var hasOpen = recent.Any(r => ProductionStates.IsOpen(r.State)) || await HasPendingImportAsync(recent, now, ct);

        var buffer = cp.Replenishing ? Math.Max(cp.TargetDays, cp.BufferDays) : cp.BufferDays;
        var decision = ReorderPoint.Evaluate(m.Stock, hasOpen, new ReorderOptions(m.PostsPerDay, buffer, cp.TargetDays, cp.MaxOrder));
        if (!decision.ShouldOrder)
        {
            if (cp.Replenishing && !hasOpen) await configs.SetReplenishingAsync(cp.CampaignId, false, ct);
            if (!hasOpen) await actions.ResolveByRefAsync(ActionKinds.ProductionBlocked, cp.CampaignId, ct);
            return false;
        }

        if (recent.FirstOrDefault(r => r.AutoGenerated && r.State != ProductionState.Cancelled) is { } last
            && Unproductive.Contains(last.State) && now - last.UpdatedUtc < FailureCooldown)
        {
            notes.Add($"\"{name}\": yêu cầu gần nhất {last.State}, chờ {FailureCooldown.TotalMinutes:0} phút trước khi đặt lại.");
            return false;
        }

        var topic = PickTopic(cp.Topics, recent);
        var aspect = cp.Aspect ?? AspectOf(plan.Rules);
        var language = cp.Language ?? plan.Rules.Select(r => r.Language).FirstOrDefault(l => !string.IsNullOrWhiteSpace(l))?.Trim() ?? "vi";
        var result = await production.CreateAsync(new NewProductionRequest(topic, language, aspect, TargetDuration(plan.Rules), null, cp.CampaignId,
            $"Tự đặt cho chiến dịch \"{name}\": tồn {m.Stock}, tiêu thụ {m.PostsPerDay:0.##} bài/ngày.", Auto: true, PreferredProducer: cp.PreferredProducer), ct);

        if (result.Request is null)
        {
            notes.Add($"\"{name}\": {result.Error}");
            if (result.Blocking)
                await actions.RaiseAsync(ActionKinds.ProductionBlocked, cp.CampaignId,
                    $"Chiến dịch \"{name}\" cần sản xuất thêm nội dung nhưng không đặt được", result.Error ?? "", ct);
            logger.LogInformation("Không đặt được sản xuất cho {Campaign}: {Reason}", name, result.Error);
            return false;
        }
        await actions.ResolveByRefAsync(ActionKinds.ProductionBlocked, cp.CampaignId, ct);
        if (!cp.Replenishing) await configs.SetReplenishingAsync(cp.CampaignId, true, ct);
        return true;
    }

    /// <summary>Completed nhưng nội dung chưa vào kho (trong thời gian ân hạn): vẫn coi là đang chờ để không đặt trùng.</summary>
    private async Task<bool> HasPendingImportAsync(IReadOnlyList<ProductionRequest> recent, DateTimeOffset now, CancellationToken ct)
    {
        var completed = recent.Where(r => r.State == ProductionState.Completed && now - r.UpdatedUtc < ImportGrace).ToList();
        if (completed.Count == 0) return false;
        var linked = await requests.LinkedContentCountsAsync(completed.Select(r => r.Id).ToList(), ct);
        return completed.Any(r => linked.GetValueOrDefault(r.Id) == 0);
    }

    /// <summary>Luân phiên theo lần dùng gần nhất: chủ đề chưa dùng hoặc dùng lâu nhất; cùng mức thì theo thứ tự danh sách.</summary>
    public static string PickTopic(IReadOnlyList<string> topics, IReadOnlyList<ProductionRequest> recentNewestFirst)
    {
        var best = topics[0];
        var bestAge = -1;
        foreach (var t in topics)
        {
            var idx = recentNewestFirst.ToList().FindIndex(r => r.State != ProductionState.Cancelled
                                                                 && string.Equals(r.Topic, t, StringComparison.OrdinalIgnoreCase));
            var age = idx < 0 ? int.MaxValue : idx;
            if (age > bestAge) (best, bestAge) = (t, age);
        }
        return best;
    }

    private static string AspectOf(IReadOnlyList<CampaignRule> rules) =>
        rules.Select(r => r.Aspect).FirstOrDefault(a => a != AspectFilter.Any) == AspectFilter.Portrait
            ? ProductionAspects.Portrait : ProductionAspects.Landscape;

    private static int? TargetDuration(IReadOnlyList<CampaignRule> rules) =>
        rules.FirstOrDefault(r => r.MinDurationSec is not null && r.MaxDurationSec is not null) is { } r
            ? (r.MinDurationSec!.Value + r.MaxDurationSec!.Value) / 2 : null;

    // --- Đo tồn ---

    private async Task<Dictionary<string, CampaignPlan>> LoadPlansAsync(CancellationToken ct)
    {
        var rules = (await campaigns.ListRulesAsync(null, ct)).ToLookup(r => r.CampaignId);
        var policies = (await campaigns.ListPoliciesAsync(null, ct)).ToDictionary(p => p.CampaignId);
        return (await campaigns.ListAsync(ct)).ToDictionary(c => c.Id,
            c => new CampaignPlan(c, rules[c.Id].ToList(), policies.GetValueOrDefault(c.Id) ?? new SchedulePolicy { CampaignId = c.Id }));
    }

    /// <summary>
    /// Mỗi kênh đích: tiêu thụ = min(slot/tuần ÷ 7, tối đa/ngày); tồn = nội dung khớp quy tắc của kênh, chưa hết hạn, chưa đăng/xếp lịch trên kênh.
    /// Chiến dịch dùng kênh tiêu thụ nhanh nhất và tồn của kênh thiếu nhất (kênh đó cạn trước).
    /// </summary>
    private async Task<Dictionary<string, StockMeasure>> MeasureAsync(IReadOnlyDictionary<string, CampaignPlan> plans, CancellationToken ct)
    {
        var now = clock.UtcNow;
        var dests = (await destinations.ListAsync(null, true, ct)).Where(d => d.RemovedUtc is null && d.Enabled).Select(d => d.Id).ToHashSet();
        var items = await contents.ListReadyAsync(ct);
        var tags = items.ToDictionary(i => i.Id, i => (IReadOnlyList<string>)PublishText.ParseTags(i.TagsJson));
        var postsByDest = (await campaigns.ListChannelPostsAsync(ct)).ToLookup(p => p.DestinationId);

        var result = new Dictionary<string, StockMeasure>();
        foreach (var plan in plans.Values)
        {
            var c = plan.Campaign;
            var perDest = new List<StockMeasure>();
            foreach (var destId in plan.Rules.SelectMany(r => r.DestinationIds).Distinct().Where(dests.Contains))
            {
                var posts = postsByDest[destId].ToList();
                var stock = items.Count(i =>
                    plan.Rules.Any(r => r.DestinationIds.Contains(destId) && r.Matches(i, tags[i.Id]))
                    && !(c.ContentMaxAgeDays is { } d && i.ImportedUtc.AddDays(d) <= now)
                    && !posts.Any(p => p.ContentItemId == i.Id && (!c.Evergreen || now - p.AtUtc < TimeSpan.FromDays(c.EvergreenMinDays))));
                var rate = Math.Min(plan.Policy.SlotsFor(destId).Count / 7.0, plan.Policy.MaxPerDay);
                perDest.Add(new StockMeasure(stock, rate));
            }
            if (perDest.Count > 0) result[c.Id] = new StockMeasure(perDest.Min(x => x.Stock), perDest.Max(x => x.PostsPerDay));
        }
        return result;
    }

    // --- UI ---

    public async Task<CampaignProductionView> GetAsync(string campaignId, CancellationToken ct)
    {
        var plans = await LoadPlansAsync(ct);
        if (!plans.TryGetValue(campaignId, out var plan)) throw new PublishingException(PublishingErrors.NotFound, "Không tìm thấy chiến dịch.");
        var cp = await configs.GetCampaignAsync(campaignId, ct) ?? new CampaignProduction { CampaignId = campaignId };
        var m = (await MeasureAsync(new Dictionary<string, CampaignPlan> { [campaignId] = plan }, ct)).GetValueOrDefault(campaignId) ?? new StockMeasure(0, 0);
        return new CampaignProductionView(cp, m, await requests.CountOpenAsync(null, campaignId, ct));
    }

    public async Task<CampaignProductionView> SetAsync(CampaignProduction r, CancellationToken ct)
    {
        if (await campaigns.GetAsync(r.CampaignId, ct) is null) throw new PublishingException(PublishingErrors.NotFound, "Không tìm thấy chiến dịch.");
        var topics = r.Topics.Select(t => t?.Trim() ?? "").Where(t => t.Length > 0).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        if (topics.Count > 100 || topics.Any(t => t.Length > ProductionService.MaxTopic))
            throw Invalid($"Tối đa 100 chủ đề, mỗi chủ đề ≤ {ProductionService.MaxTopic} ký tự.");
        if (r.Enabled && topics.Count == 0) throw Invalid("Bật tự đặt sản xuất cần ít nhất một chủ đề.");
        if (r.Aspect is not null && !ProductionAspects.IsValid(r.Aspect)) throw Invalid("Tỉ lệ phải là 16:9 hoặc 9:16.");
        if (r.PreferredProducer is not null && !Producers.IsKnown(r.PreferredProducer)) throw Invalid("Producer ưu tiên không hợp lệ.");
        if (!(r.BufferDays > 0 && r.BufferDays <= 365)) throw Invalid("Ngày đệm phải trong (0, 365].");
        if (!(r.TargetDays > 0 && r.TargetDays <= 365)) throw Invalid("Mức tồn mục tiêu (ngày) phải trong (0, 365].");
        if (r.MaxOrder is < 1 or > 100) throw Invalid("Trần đặt hàng phải trong 1..100.");
        var language = string.IsNullOrWhiteSpace(r.Language) ? null : r.Language.Trim();
        if (language is { Length: > ProductionService.MaxLanguage }) throw Invalid("Ngôn ngữ quá dài.");

        await configs.SaveCampaignAsync(new CampaignProduction
        {
            CampaignId = r.CampaignId, Enabled = r.Enabled, Topics = topics, Language = language, Aspect = r.Aspect,
            BufferDays = r.BufferDays, TargetDays = r.TargetDays, MaxOrder = r.MaxOrder, PreferredProducer = r.PreferredProducer
        }, clock.UtcNow, ct);
        return await GetAsync(r.CampaignId, ct);
    }

    private static PublishingException Invalid(string message) => new(PublishingErrors.InvalidRequest, message);
}
